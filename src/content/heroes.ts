// Héros à colorier (personnages ORIGINAUX, inspirés de grands archétypes : ninja, pirate, magicienne,
// créatures des éléments… sans reprendre de personnages existants).
//
// Dessin : 12 colonnes × 14 lignes.
//   '.' = vide   'k' = contour noir (déjà dessiné)   'e' = yeux (déjà dessinés, ils clignent)
//   toute autre lettre = une zone à colorier, numérotée dans l'ordre de `palette`.
// Pour ajouter un héros : copier un bloc, redessiner les lignes, choisir les couleurs.

export type Effect = 'shuriken' | 'coins' | 'energy' | 'stars' | 'fire' | 'bubbles' | 'bolt' | 'flowers' | 'gears';
export type Move = 'jump' | 'wobble' | 'float' | 'squash' | 'shake';

export interface Hero {
  id: string;
  name: string;
  /** « le petit ninja » — dit après le nom */
  title: string;
  /** phrase dite quand on le montre */
  line: string;
  palette: Record<string, { color: string; name: string }>;
  rows: string[];
  effect: Effect;
  move: Move;
}

